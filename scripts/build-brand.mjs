#!/usr/bin/env node
/**
 * Generate the Sales OS copies of the shared brand config and the copy gate.
 *
 * The Sales OS is deployed from inside sales/ (see deploy-sales-os.sh), so its files cannot
 * import anything above that folder. brand.config.mjs lives at the website root, where the
 * public Pages functions and the Node scripts import it. This script writes the copies:
 *
 *   sales/brand-data.js                 window.BRAND_CONFIG and helpers, from brand.config.mjs
 *   sales/functions/_lib/brand.js       byte copy of brand.config.mjs for the edge functions
 *   sales/copy-rules.js                 window.COPY_RULES, from sales/functions/_lib/copy-rules.js
 *
 * The same pattern as sales/tokens.css (mirror of scripts/sales-tokens.src.css). Edit the
 * sources, run this (build.mjs does), commit the generated files. Pass --check to verify
 * without writing; exits 1 if a generated file is stale.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const read = (p) => readFileSync(join(ROOT, p), "utf8");

const brandSrc = read("brand.config.mjs");
const rulesSrc = read("sales/functions/_lib/copy-rules.js");
const strip = (src) => src.replace(/^export\s+(const|function|async function|let)\s/gm, "$1 ");

const names = [...brandSrc.matchAll(/^export\s+(?:const|function)\s+(\w+)/gm)].map((m) => m[1]);
const ruleNames = [...rulesSrc.matchAll(/^export\s+(?:const|function)\s+(\w+)/gm)].map((m) => m[1]);

const out = {
  "sales/brand-data.js":
    `/* GENERATED by scripts/build-brand.mjs from brand.config.mjs. Edit the source, not this file. */\n` +
    `(function(){\n${strip(brandSrc)}\nwindow.BRAND_CONFIG = BRAND_CONFIG;\n` +
    `window.BRAND_FN = { ${names.filter((n) => n !== "BRAND_CONFIG").join(", ")} };\n})();\n`,
  "sales/functions/_lib/brand.js":
    `/* GENERATED by scripts/build-brand.mjs: an exact copy of website/brand.config.mjs for the Sales OS edge\n` +
    `   functions (they are deployed from sales/ and cannot import the website root). Edit the source. */\n` + brandSrc,
  "sales/copy-rules.js":
    `/* GENERATED by scripts/build-brand.mjs from sales/functions/_lib/copy-rules.js. Edit the source, not this file. */\n` +
    `(function(){\n${strip(rulesSrc.replace(/^import .*$/m, "const BRAND_CONFIG = window.BRAND_CONFIG;"))}\n` +
    `window.COPY_RULES = { ${ruleNames.join(", ")} };\n})();\n`,
};

let stale = 0;
for (const [rel, text] of Object.entries(out)) {
  const path = join(ROOT, rel);
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === text) continue;
  stale++;
  if (CHECK) console.error(`✗ build-brand: ${rel} is out of date. Run node scripts/build-brand.mjs`);
  else { writeFileSync(path, text); console.log(`• build-brand: wrote ${rel}`); }
}
if (CHECK && stale) process.exit(1);
if (!stale) console.log("build-brand: generated files current");
